"""Run one AnalogGym deck through BOTH simulators and score them side by side.

This is the layer that closes the loop: ``translate`` turns a deck into a
PyCircuitSim netlist plus :class:`AnalysisPlan` data, ``measure`` turns a
:class:`SweepResult` into metrics, and this module produces the two
``SweepResult``s -- one per simulator -- and puts three metric columns next to
each other:

``py``
    ``measure`` over PyCircuitSim's own solve.
``ng``
    ``measure`` over NGSPICE's solve, read back from an ASCII rawfile dumped by
    the reference runner (``tools/meas.run_deck``).
``ng_meas``
    NGSPICE's OWN ``.meas`` values from the same run.

``py`` vs ``ng`` is the number that matters: both go through one measurement
implementation, so a difference there is physics or numerics and can never be a
difference in what ``AVG from=-40 to=125`` was taken to mean.  ``ng`` vs
``ng_meas`` is the control that proves the measurement engine agrees with
NGSPICE on NGSPICE's own data; if that column disagrees, nothing else in the
row can be trusted.

Only LEVEL=72 (BSIM-CMG via PyCMG/OSDI) is involved.  No NN model family
(LEVEL=73/74/75) is imported, instantiated or invoked.

DC QUALITY IS THE WHOLE GAME
----------------------------
A probe established that PyCircuitSim's AC machinery is essentially exact --
solved about NGSPICE's operating point the pilot amplifier's dcgain lands within
0.004 dB and its GBW ratio at 1.0000 -- and that the entire error budget is the
DC operating point.  Two consequences are baked into this module:

* ``DCSolver._last_solve_converged`` is NOT accepted as evidence.  The
  operating-point delta against NGSPICE is a first-class output field
  (``op_delta``), computed node by node: for a dc sweep over EVERY solved
  point, for ac/tran against a dedicated NGSPICE ``op`` run.  A metric that
  matches for the wrong reason is worse than a reported failure.
* the DC solve is seeded from the deck's own ``.nodeset`` and run with the
  ``dv_limit`` trust region (see :data:`DEFAULT_MAX_ITERATIONS` and
  ``DCSolver(dv_limit=...)``), because without a per-iteration voltage cap the
  LEVEL=72 path hands OSDI a gate voltage of -505225 V and the compact model
  raises.

Both simulators' grids are generated by NGSPICE's own algorithms
(:func:`plan_points`), verified against real dumps: a decade AC sweep by
repeated multiplication (agrees to 4.3e-16), a dc sweep as
``floor((stop-start)/step) + 1`` accumulated points (which is why ``dc temp 25
20 -0.1`` stops at 20.1 and not at 20.0, in both simulators).

MEASURED STATE (tsmc5 pilot, one deck per family)
-------------------------------------------------
What this module found, so the next reader does not re-derive it:

* ``amplifier/Alfio_RAFFC_Pin_3/tb_gain.cir`` (AC, 24 devices, 221 points) --
  8/8 metrics agree; dcgain to 3.9e-5 relative, GBW to 6.9e-6, true phase
  margin to 3.1e-7.  Operating point within 110 uV worst / 25 uV rms of NGSPICE
  over all 19 nodes.  2.15 s against NGSPICE's 0.32 s.
  ``ldo/ldo_1/tb_loop_max.cir`` behaves the same way (8/8, 8.1 s, operating
  point within 91 uV) with ONE outlier worth watching: its ``dcgain_max`` reads
  75.33 dB against 74.12 dB, a 1.6 % relative gap that passes the 2 % default
  but is four orders of magnitude looser than every other AC metric measured.
* ``ldo/ldo_1/tb_load.cir`` (dc source sweep, 101 points) -- 11/11 metrics
  agree; operating point within 148 uV worst / 23 uV rms over 1111 node
  comparisons.  At PyCircuitSim's OWN tolerances (RELTOL 1e-4) the same run
  produced the same values while its convergence flag rejected all 101 points;
  at NGSPICE's tolerances all 101 pass.  Hence :data:`NGSPICE_RELTOL`, and hence
  the flag being reported rather than obeyed.  681 s against NGSPICE's 0.29 s.
* ``sensing_front_end/ptat_1/tb_dc.cir`` (dc temp, 281 points) -- agrees above
  ~50 C (vout50 to 2e-5) and is wrong below it, because PyCircuitSim's LEVEL=72
  returns EXACTLY 0 A at NGSPICE's own operating point once Vgs falls under
  ~60 mV (measured: id = 0.0 A at Vgs = 55.3 mV, id = 2.16 nA at Vgs =
  61.9 mV).  A weak-inversion stack whose devices all read zero current has no
  operating point to find, so the whole PTAT / voltage-reference family is
  blocked on that floor, not on anything here.
* ``charge_pump/chargepump/tb_tran.cir`` (transient, 41 devices) -- dies at the
  FIRST timestep at every dt tried (2 ps, 20 ps, 200 ps, 1 ns), with NR pinned
  at the ``dv_limit`` cap for all 200 iterations.  A per-iteration node-delta
  cap bounds the STEP, not the terminal voltage, so six capped iterations still
  walk a gate to -2.96 V and a drain to +3.94 V on a 0.65 V rail and OSDI
  rejects it.  Fixing this needs SPICE-style per-terminal limiting inside
  ``models/mosfet_cmg.py`` (bound Vgs/Vds/Vbs themselves), which does not exist:
  the LEVEL=72 path hands OSDI raw node voltages.
* ``amplifier/Alfio_RAFFC_Pin_3/tb_dc.cir`` (dc temp, 1651 points, run at
  ``--stride 25``) -- 0/15 metrics, and the ``op_delta`` says why rather than
  leaving it to be guessed: 9.75 V worst / 2.25 V rms node error on a 0.65 V
  rail, ``ivdd25`` of 17 kA.  The FIRST point of this bench is 125 C
  (``dc temp 125 -40 -0.1``) and it diverges there, after which the
  continuation carries the garbage down the whole sweep.  Same subcircuit,
  same devices, as the ``tb_gain`` deck that agrees to 4e-5 -- so this is the
  bench's Newton start, not the model.  ``finalize.py`` hits the same wall in
  NGSPICE on some designs and answers it by sweeping OUTWARD from the qualified
  25 C point; :func:`translate.recovery_decks` already emits exactly those
  segments, and wiring them in is the obvious next step for this family.
* ``amplifier/.../tb_tran.cir`` (transient, at ``--stride 20``) -- transients are
  NOT uniformly broken: this one commits 119 of 221 steps and its settled levels
  match NGSPICE to 3e-7 (``v_pre``, ``v_high``), then NR exhausts on the falling
  slew edge and the partial waveform is recovered and measured.  The slew
  metrics are off by 21 % because ``--stride 20`` asks for a 100 ns timestep on a
  deck written for 5 ns; that is the stride, not the simulator.
"""

