def _designs(root: Path, tech: str, category: str) -> List[Path]:
    """Every built design of one category, in sorted order."""
    cdir = root / f"designs_{tech.lower()}" / category
    if not cdir.is_dir():
        raise SimFailure(f"No such category directory: {cdir}")
    return [d for d in sorted(cdir.iterdir())
            if d.is_dir() and (d / "netlist.spice").exists()]


def _decks_of(category: str, design_dir: Path) -> List[str]:
    """Deck names of one design that exist on disk, in table order."""
    return [deck for deck in translate.build_controls(category, design_dir)
            if (design_dir / deck).exists() and deck != "tb_tran_altns.cir"]


def _print_row(row: Dict[str, Any]) -> None:
    """One line per deck plus the per-metric table."""
    verdict = row["verdict"]
    head = (f"{row['tech']}/{row['category']}/{row['design']}/{row['deck']}")
    print(f"\n=== {head} ===")
    for side in ("pycircuitsim", "ngspice"):
        error = row[side]["error"]
        print(f"  {side:13s} {row[side]['seconds']:8.2f}s"
              + (f"  ERROR {error}" if error else ""))
    for summary in row["pycircuitsim"]["sweeps"]:
        print(f"    py {summary['kind']:9s} points={summary['points']} "
              f"solved={summary['solved']} no_solution={summary['failed']} "
              f"flag_ok={summary['flag_ok']} "
              f"dc_conv={summary['dc_converged']} stride={summary['stride']} "
              f"truncated={summary['truncated_at']}")
        for failure in summary["failures"]:
            print(f"      FAIL at x={failure['x']}: {failure['error']}")
    op = row.get("op_delta") or {}
    if op.get("worst_abs") is not None:
        print(f"  op_delta ({op.get('source')}): worst "
              f"{op['worst_abs']:.6g} V at {op['worst_node']}, rms "
              f"{op['rms']:.3g} V over {op['n_compared']} comparisons")
    elif op:
        print(f"  op_delta: {op}")
    for grid in row["grid"]:
        print(f"  grid: py={grid['py_points']} ng={grid['ng_points']} "
              f"max_rel_dev={grid['max_rel_dev']}")

    table = row["compare"]["py_vs_ng"]
    engine = row["compare"]["ng_vs_ngmeas"]
    print(f"  {'metric':26s} {'pycircuitsim':>15s} {'ngspice':>15s} "
          f"{'rel':>10s}  {'ng_meas':>15s} {'eng_rel':>9s}")
    for key in sorted(table):
        entry = table[key]
        eng = engine.get(key, {})
        print(f"  {key:26s} {_fmt(entry['a']):>15s} {_fmt(entry['b']):>15s} "
              f"{_fmt(entry['rel'], '.3e'):>10s}  "
              f"{_fmt(eng.get('b')):>15s} {_fmt(eng.get('rel'), '.1e'):>9s}"
              + ("" if entry["ok"] else "  <-- differs"))
    print(f"  VERDICT agree {verdict['agree']}/{verdict['measured']}, "
          f"missing_py {verdict['missing_py']}, "
          f"engine {verdict['engine_agree']}/{verdict['engine_measured']}, "
          f"py {verdict['py_seconds']:.1f}s ng {verdict['ng_seconds']:.1f}s")


def _fmt(value: Any, spec: str = ".6g") -> str:
    if value is None:
        return "-"
    try:
        return format(float(value), spec)
    except (TypeError, ValueError):
        return str(value)


def main(argv: Optional[Sequence[str]] = None) -> int:
    """CLI: one deck, one design, or a whole category."""
    parser = argparse.ArgumentParser(
        description="Score AnalogGym decks: PyCircuitSim vs NGSPICE "
                    "(BSIM-CMG LEVEL=72 both sides).")
    parser.add_argument("--root", type=Path, default=BENCH_ROOT,
                        help="tree holding designs_tsmc* (default: %(default)s)")
    parser.add_argument("--tech", default="tsmc5",
                        help="tech tag, e.g. tsmc5 (default: %(default)s)")
    parser.add_argument("--category", required=True, choices=sorted(CONTROLS),
                        help="AnalogGym category")
    parser.add_argument("--design", default=None,
                        help="one design directory name (default: all)")
    parser.add_argument("--deck", default=None,
                        help="one deck, e.g. tb_gain.cir (default: all)")
    parser.add_argument("--out", type=Path, default=None,
                        help="JSON output directory "
                             "(default: <root>/pycircuitsim_bench_results)")
    parser.add_argument("--work", type=Path, default=None,
                        help="scratch directory for netlists/rawfiles "
                             "(default: <out>/work)")
    parser.add_argument("--stride", type=int, default=1,
                        help="keep every Nth sweep point / multiply the "
                             "transient dt by N (default: 1)")
    parser.add_argument("--max-seconds", type=float, default=None,
                        help="wall-clock budget per PyCircuitSim dc sweep; "
                             "the run truncates and says so")
    parser.add_argument("--dv-limit", type=float, default=None,
                        help="per-iteration |dV| cap in volts "
                             "(default: one supply rail; 0 disables)")
    parser.add_argument("--max-iterations", type=int,
                        default=DEFAULT_MAX_ITERATIONS,
                        help="NR budget per DC point (default: %(default)s)")
    parser.add_argument("--source-stepping", action="store_true",
                        help="enable source-stepping homotopy (measured: "
                             "25s slower, same answer, once dv_limit is on)")
    parser.add_argument("--solver-reltol", type=float, default=NGSPICE_RELTOL,
                        help="NR relative tolerance (default: NGSPICE's "
                             "%(default)s; a deck's .options still wins)")
    parser.add_argument("--solver-vntol", type=float, default=NGSPICE_VNTOL,
                        help="NR absolute voltage tolerance in volts "
                             "(default: NGSPICE's %(default)s)")
    parser.add_argument("--ng-timeout", type=float, default=1800.0,
                        help="NGSPICE timeout in seconds (default: %(default)s)")
    parser.add_argument("--rtol", type=float, default=0.02,
                        help="metric agreement tolerance (default: %(default)s)")
    parser.add_argument("--no-recovery", action="store_true",
                        help="do not fall back to the outward-from-25 C "
                             "segments when a monolithic temperature sweep "
                             "loses its Newton branch (amplifier tb_dc only)")
    args = parser.parse_args(argv)
    _pin_design_tree(args.root, args.tech)

    out_dir = args.out or (args.root / "pycircuitsim_bench_results")
    work_root = args.work or (out_dir / "work")
    opts = SimOptions(
        dv_limit=args.dv_limit, max_iterations=args.max_iterations,
        use_source_stepping=args.source_stepping,
        reltol=args.solver_reltol, vntol=args.solver_vntol,
        stride=args.stride, max_seconds=args.max_seconds,
        ng_timeout=args.ng_timeout)

    designs = ([args.root / f"designs_{args.tech.lower()}" / args.category
                / args.design] if args.design
               else _designs(args.root, args.tech, args.category))

    failures = 0
    for design_dir in designs:
        decks = [args.deck] if args.deck else _decks_of(args.category,
                                                        design_dir)
        for deck in decks:
            work = work_root / args.tech.lower() / design_dir.name
            try:
                row = compare_deck(design_dir, deck, tech=args.tech.lower(),
                                   category=args.category, work=work,
                                   opts=opts, rtol=args.rtol,
                                   recovery=not args.no_recovery)
            except Exception as exc:                # noqa: BLE001 -- reported
                failures += 1
                print(f"\n=== {args.tech}/{args.category}/{design_dir.name}/"
                      f"{deck} ===\n  TRANSLATE/RUN ERROR "
                      f"{type(exc).__name__}: {exc}")
                continue
            _print_row(row)
            write_result(row, out_dir)
            if not row["verdict"]["ran"] or not row["verdict"]["ng_ran"]:
                failures += 1
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
